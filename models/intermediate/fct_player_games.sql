WITH MAIN_CTE AS (
    SELECT
        C.GAME_ID::VARCHAR AS GAME_ID,
        C.GAME_TYPE_SECS::VARCHAR AS GAME_TYPE_SECS,
        C.WHITE_PLAYER::VARCHAR AS WHITE_PLAYER,
        C.WHITE_PLAYER_ELO::VARCHAR AS WHITE_PLAYER_ELO,
        C.BLACK_PLAYER::VARCHAR AS BLACK_PLAYER,
        C.BLACK_PLAYER_ELO::VARCHAR AS BLACK_PLAYER_ELO,
        C.START_DATETIME_UTC::TIMESTAMP AS START_DATETIME_UTC,
        C.END_DATETIME_UTC::TIMESTAMP AS END_DATETIME_UTC,
        DATEDIFF(SECOND, C.START_DATETIME_UTC, C.END_DATETIME_UTC) AS DURATION_SECS,
        E.ECO_ID::VARCHAR AS ECO_ID,
        C.GAME_RESULT::VARCHAR AS GAME_RESULT,
        C.TERMINATION::VARCHAR AS TERMINATION,
        C.GAME_URL::VARCHAR AS GAME_URL
    FROM {{ ref('stg_chess_matches')}} AS C
    INNER JOIN {{ ref ('dim_eco')}} AS E
    ON C.ECO_URL = E.ECO_URL
    INNER JOIN {{ ref ('dim_time_controls')}} AS T
    ON C.GAME_TYPE_SECS = T.GAME_TYPE_SECS

    {% if is_incremental() %}
    WHERE C.GAME_ID NOT IN (SELECT GAME_ID FROM {{ this }})
    {% endif %}),

    PLAYER_CTE AS (
    SELECT
        M.GAME_ID::VARCHAR AS GAME_ID,
        P.PLAYER_ID::VARCHAR AS PLAYER_ID,
        CASE 
            WHEN M.WHITE_PLAYER = P.PLAYER_ID THEN 'White'
            WHEN M.BLACK_PLAYER = P.PLAYER_ID THEN 'Black'
        END AS PLAYER_SIDE,
        CASE 
            WHEN M.WHITE_PLAYER = P.PLAYER_ID THEN M.WHITE_PLAYER_ELO
            WHEN M.BLACK_PLAYER = P.PLAYER_ID THEN M.BLACK_PLAYER_ELO
        END AS PLAYER_ELO,
        CASE 
            WHEN M.WHITE_PLAYER = P.PLAYER_ID THEN M.BLACK_PLAYER
            WHEN M.BLACK_PLAYER = P.PLAYER_ID THEN M.WHITE_PLAYER
        END AS OPPONENT_ID,
        CASE 
            WHEN M.WHITE_PLAYER = P.PLAYER_ID THEN M.BLACK_PLAYER_ELO
            WHEN M.BLACK_PLAYER = P.PLAYER_ID THEN M.WHITE_PLAYER_ELO
        END AS OPPONENT_ELO 
    FROM MAIN_CTE AS M
    INNER JOIN {{ ref('dim_players') }} AS P
    ON P.PLAYER_ID IN (M.WHITE_PLAYER, M.BLACK_PLAYER)
    )

SELECT
    M.GAME_ID,
    M.GAME_TYPE_SECS,
    P.PLAYER_ID,
    P.PLAYER_ELO,
    P.PLAYER_SIDE,
    P.OPPONENT_ID,
    P.OPPONENT_ELO,
    M.START_DATETIME_UTC,
    M.END_DATETIME_UTC,
    M.DURATION_SECS,
    M.ECO_ID,
    M.GAME_RESULT,
    M.TERMINATION,
    M.GAME_URL
FROM MAIN_CTE AS M
INNER JOIN PLAYER_CTE AS P
ON M.GAME_ID = P.GAME_ID
